"""
Centralized embedding generation with provider abstraction, retry/backoff,
and usage tracking.

Why this module exists
----------------------
Before this, embeddings were called directly against the OpenAI client inside
request handlers (modules/whatsapp/knowledge_service.py). A single OpenAI
outage or quota exhaustion (HTTP 429 insufficient_quota) silently broke the
whole WhatsApp sales bot: FAQs could not embed, so the knowledge base stayed
empty and the bot went mute. Those failures were also invisible because the
embeddings path bypassed the central `track_usage` sink.

This module fixes both:
  * The active provider is configurable (EMBEDDING_PROVIDER) so an outage is a
    one-line env change + re-embed, not a code change.
  * Transient errors (timeouts, connection drops, 5xx, non-quota rate limits)
    are retried with exponential backoff. Permanent errors (quota/auth) fail
    fast with a clear message instead of retrying uselessly.
  * Every call is recorded through `track_usage`, closing the observability gap.

IMPORTANT — embeddings are NOT interchangeable per-call.
Each provider/model produces vectors in its own space, so a query embedded with
provider A will not match documents embedded with provider B. There is
therefore ONE active provider for both indexing and querying. Switching
providers requires re-embedding the knowledge base (see
KnowledgeService.sync_all_faqs_to_knowledge / sync_products_to_knowledge).
`EMBEDDING_FALLBACK_PROVIDERS` exists only for hard-outage failover and logs a
loud warning because it degrades search quality until a full re-embed.
"""

import logging
import os
import time
from typing import List, Optional

logger = logging.getLogger(__name__)

# Model names per provider (kept here so callers can record which model
# produced a given row via active_embedding_model()).
_OPENAI_MODEL = os.getenv("OPENAI_EMBEDDING_MODEL", "text-embedding-3-small")
_GEMINI_MODEL = os.getenv("GEMINI_EMBEDDING_MODEL", "gemini-embedding-001")
_AZURE_DEPLOYMENT = os.getenv("AZURE_OPENAI_EMBEDDING_DEPLOYMENT", "text-embedding-3-small")
# Local (self-hosted) provider: fastembed / ONNX, CPU-only, no API key, cannot
# be quota-suspended. Default so the platform has NO hard external dependency.
_LOCAL_MODEL = os.getenv("LOCAL_EMBEDDING_MODEL", "BAAI/bge-small-en-v1.5")

# Output dimension per provider. The active provider's dimension MUST match the
# company_knowledge.embedding column. Switching to a provider of a different
# dimension is a migration (ALTER column + full re-embed), not a hot swap.
_PROVIDER_DIMS = {
    "openai": 1536,
    "azure_openai": 1536,
    "gemini": 1536,
    "local": 384,   # BAAI/bge-small-en-v1.5
}


def active_dim() -> int:
    return _PROVIDER_DIMS.get(active_provider(), 384)


# Dimension of the active provider, imported by callers/models for validation.
EMBEDDING_DIM = _PROVIDER_DIMS.get(
    (os.getenv("EMBEDDING_PROVIDER") or "local").strip().lower(), 384
)

_MAX_ATTEMPTS = int(os.getenv("EMBEDDING_MAX_ATTEMPTS", "3"))
_BASE_BACKOFF = float(os.getenv("EMBEDDING_BACKOFF_SECONDS", "0.5"))


class EmbeddingError(RuntimeError):
    """Raised when embeddings cannot be generated by any configured provider."""


class _PermanentProviderError(Exception):
    """Provider failed in a way retries won't fix (quota exhausted, bad auth)."""


# ---------------------------------------------------------------------------
# Provider configuration
# ---------------------------------------------------------------------------

def active_provider() -> str:
    """The single provider used for BOTH indexing and querying.

    Defaults to the self-hosted 'local' model so the bot keeps working even if
    every external AI provider is down or unfunded.
    """
    return (os.getenv("EMBEDDING_PROVIDER") or "local").strip().lower()


def _fallback_providers() -> List[str]:
    raw = os.getenv("EMBEDDING_FALLBACK_PROVIDERS", "")
    return [p.strip().lower() for p in raw.split(",") if p.strip()]


def active_embedding_model() -> str:
    """Model identifier for the active provider (stored per knowledge row)."""
    return _model_for(active_provider())


def _model_for(provider: str) -> str:
    return {
        "openai": _OPENAI_MODEL,
        "gemini": _GEMINI_MODEL,
        "azure_openai": f"azure/{_AZURE_DEPLOYMENT}",
        "local": _LOCAL_MODEL,
    }.get(provider, provider)


# ---------------------------------------------------------------------------
# Lazy provider clients (import + construct only when first used)
# ---------------------------------------------------------------------------

_openai_client = None
_azure_client = None
_gemini_client = None
_local_model = None


def _get_local_model():
    global _local_model
    if _local_model is None:
        from fastembed import TextEmbedding
        # Loads the ONNX model (pre-downloaded into the image at build time via
        # FASTEMBED_CACHE_PATH so there is no runtime network dependency).
        cache_dir = os.getenv("FASTEMBED_CACHE_PATH") or None
        _local_model = TextEmbedding(model_name=_LOCAL_MODEL, cache_dir=cache_dir)
    return _local_model


def _get_openai_client():
    global _openai_client
    if _openai_client is None:
        from openai import OpenAI
        _openai_client = OpenAI(api_key=os.getenv("OPENAI_API_KEY"))
    return _openai_client


def _get_azure_client():
    global _azure_client
    if _azure_client is None:
        from openai import AzureOpenAI
        _azure_client = AzureOpenAI(
            api_key=os.getenv("AZURE_OPENAI_API_KEY"),
            azure_endpoint=os.getenv("AZURE_OPENAI_ENDPOINT", ""),
            api_version=os.getenv("AZURE_OPENAI_API_VERSION", "2024-02-01"),
        )
    return _azure_client


def _get_gemini_client():
    global _gemini_client
    if _gemini_client is None:
        from google import genai
        key = os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY")
        if not key:
            raise _PermanentProviderError("No GEMINI_API_KEY / GOOGLE_API_KEY set")
        _gemini_client = genai.Client(api_key=key)
    return _gemini_client


# ---------------------------------------------------------------------------
# Error classification (OpenAI / Azure share the openai SDK exception tree)
# ---------------------------------------------------------------------------

def _is_permanent_openai_error(exc: Exception) -> bool:
    """Quota exhaustion and auth failures won't be fixed by retrying."""
    code = getattr(exc, "code", None)
    if code in ("insufficient_quota", "invalid_api_key", "account_deactivated"):
        return True
    status = getattr(exc, "status_code", None)
    if status in (401, 403):
        return True
    msg = str(exc).lower()
    return "insufficient_quota" in msg or "exceeded your current quota" in msg


# ---------------------------------------------------------------------------
# Provider implementations — each returns List[List[float]] of dim 1536
# ---------------------------------------------------------------------------

def _embed_openai(texts: List[str], client) -> tuple:
    resp = client.embeddings.create(model=_OPENAI_MODEL, input=texts)
    vectors = [d.embedding for d in resp.data]
    tokens = getattr(getattr(resp, "usage", None), "prompt_tokens", 0) or 0
    return vectors, tokens


def _embed_azure(texts: List[str]) -> tuple:
    client = _get_azure_client()
    resp = client.embeddings.create(model=_AZURE_DEPLOYMENT, input=texts)
    vectors = [d.embedding for d in resp.data]
    tokens = getattr(getattr(resp, "usage", None), "prompt_tokens", 0) or 0
    return vectors, tokens


def _l2_normalize(vec: List[float]) -> List[float]:
    norm = sum(v * v for v in vec) ** 0.5
    if norm == 0:
        return vec
    return [v / norm for v in vec]


def _embed_local(texts: List[str]) -> tuple:
    """Self-hosted CPU embeddings via fastembed (ONNX). bge models are already
    L2-normalized, ideal for cosine search."""
    model = _get_local_model()
    vectors = [v.tolist() for v in model.embed(list(texts))]
    est_tokens = sum(len(t) for t in texts) // 4
    return vectors, est_tokens


def _embed_gemini(texts: List[str]) -> tuple:
    from google.genai import types
    client = _get_gemini_client()
    resp = client.models.embed_content(
        model=_GEMINI_MODEL,
        contents=texts,
        config=types.EmbedContentConfig(
            output_dimensionality=EMBEDDING_DIM,
            # Symmetric type so the same function works for docs and queries.
            task_type="SEMANTIC_SIMILARITY",
        ),
    )
    # Gemini recommends L2-normalizing when output_dimensionality != 3072.
    vectors = [_l2_normalize(list(e.values)) for e in resp.embeddings]
    est_tokens = sum(len(t) for t in texts) // 4
    return vectors, est_tokens


def _call_provider(provider: str, texts: List[str]) -> tuple:
    """Dispatch to a provider. Raises _PermanentProviderError for quota/auth."""
    try:
        if provider == "local":
            return _embed_local(texts)
        if provider == "openai":
            return _embed_openai(texts, _get_openai_client())
        if provider == "azure_openai":
            return _embed_azure(texts)
        if provider == "gemini":
            return _embed_gemini(texts)
        raise _PermanentProviderError(f"Unknown embedding provider '{provider}'")
    except _PermanentProviderError:
        raise
    except Exception as exc:  # noqa: BLE001 - classify then re-raise
        if provider in ("openai", "azure_openai") and _is_permanent_openai_error(exc):
            raise _PermanentProviderError(str(exc)) from exc
        raise


def _provider_with_retry(provider: str, texts: List[str]) -> tuple:
    """Call a single provider, retrying transient failures with backoff."""
    last_exc: Optional[Exception] = None
    for attempt in range(1, _MAX_ATTEMPTS + 1):
        try:
            return _call_provider(provider, texts)
        except _PermanentProviderError:
            raise  # don't waste retries on quota/auth
        except Exception as exc:  # noqa: BLE001
            last_exc = exc
            if attempt >= _MAX_ATTEMPTS:
                break
            delay = _BASE_BACKOFF * (2 ** (attempt - 1))
            logger.warning(
                "[embeddings] %s transient error (attempt %d/%d): %s; retrying in %.1fs",
                provider, attempt, _MAX_ATTEMPTS, exc, delay,
            )
            time.sleep(delay)
    raise EmbeddingError(f"{provider} failed after {_MAX_ATTEMPTS} attempts: {last_exc}")


def _validate(vectors: List[List[float]], expected_count: int, provider: str):
    if len(vectors) != expected_count:
        raise EmbeddingError(
            f"{provider} returned {len(vectors)} vectors, expected {expected_count}"
        )
    for v in vectors:
        if len(v) != EMBEDDING_DIM:
            raise EmbeddingError(
                f"{provider} returned dim {len(v)}, expected {EMBEDDING_DIM}. "
                "Refusing to store mismatched vectors."
            )


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def embed_texts(texts: List[str], *, agent_name: str = "knowledge_embeddings") -> List[List[float]]:
    """
    Embed a batch of texts using the active provider, with retry/backoff and
    hard-outage failover to EMBEDDING_FALLBACK_PROVIDERS. Records usage.

    Raises EmbeddingError if every configured provider fails.
    """
    if not texts:
        return []

    chain = [active_provider()] + _fallback_providers()
    errors = []
    for i, provider in enumerate(chain):
        try:
            vectors, tokens = _provider_with_retry(provider, texts)
            _validate(vectors, len(texts), provider)
            if i > 0:
                logger.error(
                    "[embeddings] FAILOVER to '%s' — vectors now mix spaces with the "
                    "primary provider; re-embed the knowledge base to restore search quality.",
                    provider,
                )
            _track(provider, tokens, agent_name, success=True)
            return vectors
        except (_PermanentProviderError, EmbeddingError) as exc:
            errors.append(f"{provider}: {exc}")
            logger.error("[embeddings] provider '%s' failed: %s", provider, exc)
            _track(provider, 0, agent_name, success=False, error=str(exc))
            continue

    raise EmbeddingError("All embedding providers failed -> " + " | ".join(errors))


def embed_text(text: str, *, agent_name: str = "knowledge_embeddings") -> List[float]:
    """Embed a single text. See embed_texts."""
    return embed_texts([text], agent_name=agent_name)[0]


def _track(provider: str, tokens: int, agent_name: str, *, success: bool, error: str = None):
    """Best-effort usage tracking via the central sink (never raises)."""
    try:
        from modules.openrouter.ai_usage_service import track_usage
        from modules.openrouter.context import ai_context
        ctx = ai_context.get()
        track_usage(
            model=_model_for(provider),
            prompt_tokens=tokens,
            completion_tokens=0,
            total_tokens=tokens,
            agent_name=agent_name,
            store_id=getattr(ctx, "store_id", None),
            user_id=getattr(ctx, "user_id", None),
            success=success,
            error_message=error,
            request_metadata={"kind": "embedding", "provider": provider},
        )
    except Exception as exc:  # noqa: BLE001
        logger.debug("[embeddings] usage tracking skipped: %s", exc)
