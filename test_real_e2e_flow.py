    scraped_data = scrape_url(url)

    brand_color = scraped_data.get("brand_color", "")
    logo_url = scraped_data.get("logo_url", "")

    # Step 2: REAL AI generation of ad sets
    print("\n" + "=" * 40)
    print("STEP 2: GENERATE AD SETS (AI)")
    print("=" * 40)
    ad_content = generate_ad_content_with_ai(scraped_data, url)

    business_name = ad_content.get("business_name", "Unknown")
    business_type = ad_content.get("business_type", "Unknown")
    ad_sets = ad_content.get("ad_sets", [])

    print(f"\n[RESULT] Business: {business_name}")
    print(f"[RESULT] Type: {business_type}")
    print(f"[RESULT] Products: {', '.join(ad_content.get('products_services', []))}")
    print(f"[RESULT] Ad Sets Generated: {len(ad_sets)}")

    for i, ad_set in enumerate(ad_sets, 1):
        print(f"\n  [{i}] {ad_set['name']}")
        print(f"      Title: {ad_set.get('title', 'N/A')}")
        print(f"      Emotion: {ad_set.get('emotion', 'N/A')}")
        print(f"      Value Prop: {ad_set.get('value_proposition', 'N/A')[:60]}...")

    # Step 3: REAL AdCreativeAgent image prompt generation
    print("\n" + "=" * 40)
    print("STEP 3: GENERATE IMAGE PROMPTS (AdCreativeAgent)")
    print("=" * 40)

    agent = AdCreativeAgent()
    results = []

    for i, ad_set in enumerate(ad_sets, 1):
        print(f"\n[{i}/{len(ad_sets)}] Generating image prompt for: {ad_set['name']}...")

        result = await agent.generate_ad_creative(
            product_name=business_name,
            product_description=f"{business_type} - {ad_set.get('value_proposition', '')}",
            target_audience=ad_set["name"],
            key_benefits=ad_set.get("features", ["Quality", "Value", "Trust"]),
            call_to_action="Shop Now" if "retail" in business_type.lower() or "fashion" in business_type.lower() else "Get Started",
            angle_name=ad_set["name"],
            angle_value_proposition=ad_set.get("value_proposition", ""),
            angle_emotion=ad_set.get("emotion", "Trust"),
            visual_direction=ad_set.get("visual_direction", ""),
            logo_url=logo_url,
            brand_color=brand_color
        )

        results.append({
            "ad_set": ad_set["name"],
            "headline": result["headline"],
            "ad_angle": result["ad_angle"],
            "image_prompt": result["image_prompt"],
            "has_color": brand_color.lower() in result["image_prompt"].lower() if brand_color else True,
            "has_logo": logo_url in result["image_prompt"] if logo_url else True,
            "tokens_used": result.get("tokens_used")
        })

        print(f"    Headline: {result['headline']}")
        print(f"    Tokens: {result.get('tokens_used')}")

    # Final Summary
    print("\n" + "=" * 80)
    print("FINAL SUMMARY")
    print("=" * 80)

    print(f"\nURL: {url}")
    print(f"Business: {business_name}")
    print(f"Type: {business_type}")
    print(f"Brand Color: {brand_color or 'None'}")
    print(f"Logo URL: {logo_url[:60]}..." if logo_url else "Logo URL: None")

    print(f"\n--- {len(results)} Ad Sets Generated (by AI, not hardcoded!) ---")
    for r in results:
        color_check = "OK" if r["has_color"] else "MISSING"
        logo_check = "OK" if r["has_logo"] else "MISSING"
        print(f"\n{r['ad_set']}:")
        print(f"  Headline: {r['headline']}")
        print(f"  Color: {color_check}, Logo: {logo_check}")
        print(f"  Prompt: {r['image_prompt'][:150]}...")

    return {
        "business_name": business_name,
        "business_type": business_type,
        "brand_color": brand_color,
        "logo_url": logo_url,
        "ad_sets_count": len(results),
        "results": results
    }


