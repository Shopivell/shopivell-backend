def scrape_url(url: str) -> dict:
    """Scrape URL using Tavily - REAL scraping, no mocks"""
    print(f"\n[SCRAPE] Scraping {url} with Tavily...")

    tavily = TavilyClient(api_key=tavily_api_key)

    # Extract domain for search
    from urllib.parse import urlparse
    parsed = urlparse(url)
    domain = parsed.netloc or parsed.path.split('/')[0]
    base_url = f"{parsed.scheme}://{domain}"

    # Search with Tavily - need actual search terms, not just site: operator
    result = tavily.search(
        query=f"{domain} products services about",
        search_depth="advanced",
        include_raw_content=True,
        include_domains=[domain],
        max_results=5
    )

    # Combine content
    all_content = []
    for r in result.get("results", []):
        if r.get("raw_content"):
            all_content.append(r["raw_content"][:5000])
        elif r.get("content"):
            all_content.append(r["content"])

    combined = "\n\n---\n\n".join(all_content)
    print(f"[SCRAPE] Got {len(combined)} chars from {len(all_content)} pages")

    # Extract branding using REAL scraping functions
    print(f"\n[BRANDING] Extracting logo and images...")
    images = _extract_images_from_website(url)
    logo_url = images.get("logo_url") or ""
    print(f"[BRANDING] Logo URL: {logo_url[:60]}..." if logo_url else "[BRANDING] Logo URL: None")
    print(f"[BRANDING] Total images found: {len(images.get('images', []))}")

    # Use Vision AI to analyze ALL images (logo, uniforms, vehicles, equipment)
    brand_color = ""
    visual_profile = {}

    print(f"\n[VISION] Analyzing images for brand colors, uniforms, vehicles, equipment...")
    vision_analysis = _analyze_images_with_vision(images, domain)

    if vision_analysis:
        # Extract brand color from logo
        if vision_analysis.get("brand_colors"):
            brand_color = vision_analysis["brand_colors"][0]
            print(f"[VISION] Brand color from logo: {brand_color}")

        # Extract visual profile (uniforms, vehicles, equipment)
        visual_profile = {
            "logo_description": vision_analysis.get("logo_description"),
            "uniform_description": vision_analysis.get("uniform_description"),
            "vehicle_description": vision_analysis.get("vehicle_description"),
            "equipment_description": vision_analysis.get("equipment_description"),
            "visual_style": vision_analysis.get("visual_profile"),
            "reference_images": vision_analysis.get("reference_images", [])
        }

        print(f"[VISION] Uniform: {visual_profile.get('uniform_description', 'Not detected')}")
        print(f"[VISION] Vehicle: {visual_profile.get('vehicle_description', 'Not detected')}")
        print(f"[VISION] Equipment: {visual_profile.get('equipment_description', 'Not detected')}")

    if not brand_color:
        print(f"[VISION] No color from logo, falling back to CSS...")
        colors = _extract_brand_colors_from_css(url)
        brand_color = colors.get("primary_color") or ""

    print(f"[BRANDING] Final Brand Color: {brand_color}")

    return {
        "url": url,
        "domain": domain,
        "content": combined[:25000],
        "pages_extracted": len(all_content),
        "logo_url": logo_url,
        "brand_color": brand_color,
        "visual_profile": visual_profile
    }


def generate_ad_content_with_ai(scraped_data: dict, url: str) -> dict:
    """Generate ad content using AI (OpenRouter/OpenAI) - REAL AI generation, no mocks"""

    content = scraped_data.get("content", "")
    domain = scraped_data.get("domain", "")
    pages_extracted = scraped_data.get("pages_extracted", 1)

    prompt = f"""You are an expert B2B/B2C digital marketing specialist creating high-converting Facebook/Instagram ad campaigns.

Website URL: {url}
Domain: {domain}
Pages Scraped: {pages_extracted}

WEBSITE CONTENT:
{content[:15000]}

STEP 1 - DEEP BUSINESS ANALYSIS:
Analyze the scraped content to identify:
1. WHAT does this business sell? (products, services, technology, etc.)
2. WHO are the BUYERS? Think about:
   - What INDUSTRIES use this product? (property management, healthcare, retail, government, etc.)
   - What JOB TITLES make purchasing decisions? (managers, directors, executives, owners)
   - What COMPANY TYPES need this? (SMEs, enterprises, government agencies, residential)
   - What PROBLEMS does each buyer type have that this product solves?
3. Extract any METRICS or STATISTICS mentioned (accuracy %, speed improvements, cost savings)

STEP 2 - GENERATE EXACTLY 5 BUYER PERSONAS (THIS IS REQUIRED):

You MUST generate exactly 5 different ad sets. Each must target a completely different buyer.

FOR B2B BUSINESSES (technology, services, enterprise solutions):
Generate 5 ad sets targeting different:
- INDUSTRY #1: One specific industry vertical
- INDUSTRY #2: Another different industry vertical
- JOB ROLE #3: A specific decision-maker role
- COMPANY TYPE #4: SME or enterprise or government
- USE CASE #5: A specific application of the product

FOR B2C BUSINESSES (retail, fashion, consumer products):
Generate 5 ad sets targeting different shopping occasions and customer types:
- SEASONAL OCCASION #1: A specific holiday or season (e.g., back-to-school season, Valentine's Day, Christmas, summer vacation, winter fashion)
- LIFE EVENT #2: A life milestone that triggers purchases (e.g., first job interview, graduation, wedding preparation, new baby)
- DEMOGRAPHIC #3: A specific customer type (e.g., young professionals, parents with kids, fashion-forward teens)
- PRODUCT CATEGORY #4: A specific product line if the business sells multiple types
- USE CASE #5: A specific occasion or need (e.g., office wear, weekend casual, party outfits, travel essentials)

CRITICAL: You MUST output exactly 5 ad sets in the ad_sets array. Not 1, not 2, not 3 - exactly 5.

STEP 3 - GENERATE AD CONTENT:

1. HEADLINES (5 different, max 40 chars each, include 2-3 relevant emojis)
   - Include specific metrics from scraped content
   - Example format: "99% Accurate ANPR System 🚗🔒" or "Smart Parking Solutions 🅿️✨"

2. DESCRIPTIONS (5 different, max 150 chars each, include emojis)
   - Address specific buyer pain points
   - Include metrics and benefits
   - End with CTA

3. AD_SETS (5 different buyer personas):

For each ad set, provide:
- name: The BUYER PERSONA (industry or role-based, 2-4 words)
- title: Headline with emojis addressing this buyer's specific pain point (max 50 chars)
- audience_description: 2-3 sentences describing WHO this buyer is (job titles, responsibilities, what they need)
- audience_tags: 15 Facebook targeting interests specific to THIS buyer persona
- primary_text: DETAILED ad copy (100-180 words) with metrics, features, and CTA with emojis
- features: 5 specific features with metrics where available
- hashtags: 8 industry-specific hashtags
- value_proposition: One sentence with specific metric
- emotion: Primary emotion (Efficiency, Security, Control, Growth, Trust)
- visual_direction: Specific scene showing THIS buyer persona using the product

Return as JSON:
{{
    "business_name": "...",
    "business_type": "...",
    "products_services": ["...", "...", "..."],
    "key_metrics": ["99% accuracy", "85% faster", "etc from scraped content"],
    "headlines": ["Headline with emojis 🚗🔒", "...", "...", "...", "..."],
    "descriptions": ["Description with metrics and emojis ✨", "...", "...", "...", "..."],
    "ad_sets": [
        {{
            "name": "Industry or Role-Based Buyer Persona",
            "title": "Headline with Emojis for This Buyer 🎯",
            "audience_description": "Detailed description of WHO this buyer is...",
            "audience_tags": ["15", "specific", "targeting", "tags"],
            "primary_text": "100-180 word detailed ad copy with metrics and emojis...",
            "features": ["feature with metric", "feature with metric", "feature", "feature", "feature"],
            "hashtags": ["8", "industry", "hashtags"],
            "value_proposition": "Specific benefit with metric",
            "emotion": "Primary emotion",
            "visual_direction": "Scene description"
        }}
    ]
}}

Return ONLY valid JSON, no markdown.
"""

    print(f"\n[AI] Generating ad content with AI...")

    # Try OpenRouter first
    if OPENROUTER_AVAILABLE:
        print("[AI] Using OpenRouter (GPT-4o)...")
        try:
            client = OpenRouterClient()
            response = client.chat_completion(
                messages=[{"role": "user", "content": prompt}],
                model="openai/gpt-4o"
            )
            response_text = response.get("choices", [{}])[0].get("message", {}).get("content", "")

            # Parse JSON
            json_match = re.search(r'\{[\s\S]*\}', response_text)
            if json_match:
                result = json.loads(json_match.group())
                print(f"[AI] Generated content for: {result.get('business_name')}")
                print(f"[AI] Business type: {result.get('business_type')}")
                print(f"[AI] Ad sets generated: {len(result.get('ad_sets', []))}")
                return result
        except Exception as e:
            print(f"[AI] OpenRouter error: {e}")

    # Fallback to OpenAI
    if OPENAI_AVAILABLE and openai_api_key:
        print("[AI] Falling back to OpenAI...")
        try:
            client = OpenAI(api_key=openai_api_key)
            response = client.chat.completions.create(
                model="gpt-4o",
                messages=[{"role": "user", "content": prompt}],
                temperature=0.7
            )
            response_text = response.choices[0].message.content

            json_match = re.search(r'\{[\s\S]*\}', response_text)
            if json_match:
                result = json.loads(json_match.group())
                print(f"[AI] Generated content for: {result.get('business_name')}")
                print(f"[AI] Business type: {result.get('business_type')}")
                print(f"[AI] Ad sets generated: {len(result.get('ad_sets', []))}")
                return result
        except Exception as e:
            print(f"[AI] OpenAI error: {e}")

    raise Exception("No AI client available!")


async def test_real_e2e_flow(url: str):
    """Test the REAL end-to-end flow with NO hardcoded data"""

    print("=" * 80)
    print("REAL END-TO-END TEST - NO HARDCODED DATA")
    print("=" * 80)
    print(f"URL: {url}")
    print(f"Time: {datetime.now().isoformat()}")
    print("=" * 80)

    # Step 1: REAL scraping with Tavily
    print("\n" + "=" * 40)
    print("STEP 1: SCRAPE URL (Tavily)")
    print("=" * 40)
    scraped_data = scrape_url(url)

    brand_color = scraped_data.get("brand_color", "")
    logo_url = scraped_data.get("logo_url", "")
    visual_profile = scraped_data.get("visual_profile", {})

    # Step 2: REAL AI generation of ad sets
    print("\n" + "=" * 40)
    print("STEP 2: GENERATE AD SETS (AI)")
    print("=" * 40)
    ad_content = generate_ad_content_with_ai(scraped_data, url)

    business_name = ad_content.get("business_name", "Unknown")
    business_type = ad_content.get("business_type", "Unknown")
    ad_sets = ad_content.get("ad_sets", [])

    print(f"\n[RESULT] Business: {business_name}")
    print(f"[RESULT] Type: {business_type}")
    print(f"[RESULT] Products: {', '.join(ad_content.get('products_services', []))}")
    print(f"[RESULT] Ad Sets Generated: {len(ad_sets)}")

    for i, ad_set in enumerate(ad_sets, 1):
        print(f"\n  [{i}] {ad_set['name']}")
        print(f"      Title: {ad_set.get('title', 'N/A')}")
        print(f"      Emotion: {ad_set.get('emotion', 'N/A')}")
        print(f"      Value Prop: {ad_set.get('value_proposition', 'N/A')[:60]}...")

    # Step 3: REAL AdCreativeAgent image prompt generation
    print("\n" + "=" * 40)
    print("STEP 3: GENERATE IMAGE PROMPTS (AdCreativeAgent)")
    print("=" * 40)

    agent = AdCreativeAgent()
    results = []

    for i, ad_set in enumerate(ad_sets, 1):
        print(f"\n[{i}/{len(ad_sets)}] Generating image prompt for: {ad_set['name']}...")

        result = await agent.generate_ad_creative(
            product_name=business_name,
            product_description=f"{business_type} - {ad_set.get('value_proposition', '')}",
            target_audience=ad_set["name"],
            key_benefits=ad_set.get("features", ["Quality", "Value", "Trust"]),
            call_to_action="Shop Now" if "retail" in business_type.lower() or "fashion" in business_type.lower() else "Get Started",
            angle_name=ad_set["name"],
            angle_value_proposition=ad_set.get("value_proposition", ""),
            angle_emotion=ad_set.get("emotion", "Trust"),
            visual_direction=ad_set.get("visual_direction", ""),
            logo_url=logo_url,
            brand_color=brand_color,
            visual_profile=visual_profile
        )

        results.append({
            "ad_set": ad_set["name"],
            "title": ad_set.get("title", ""),
            "audience_description": ad_set.get("audience_description", ""),
            "primary_text": ad_set.get("primary_text", ""),
            "value_proposition": ad_set.get("value_proposition", ""),
            "headline": result["headline"],
            "ad_angle": result["ad_angle"],
            "image_prompt": result["image_prompt"],
            "has_color": brand_color.lower() in result["image_prompt"].lower() if brand_color else True,
            "has_logo": logo_url in result["image_prompt"] if logo_url else True,
            "tokens_used": result.get("tokens_used")
        })

        print(f"    Headline: {result['headline']}")
        print(f"    Tokens: {result.get('tokens_used')}")

    # Final Summary
    print("\n" + "=" * 80)
    print("FINAL SUMMARY")
    print("=" * 80)

    print(f"\nURL: {url}")
    print(f"Business: {business_name}")
    print(f"Type: {business_type}")
    print(f"Brand Color: {brand_color or 'None'}")
    print(f"Logo URL: {logo_url[:60]}..." if logo_url else "Logo URL: None")

    print(f"\n--- {len(results)} Ad Sets Generated (by AI, not hardcoded!) ---")
    for i, r in enumerate(results, 1):
        color_check = "OK" if r["has_color"] else "MISSING"
        logo_check = "OK" if r["has_logo"] else "MISSING"
        print(f"\n{'='*70}")
        print(f"AD SET {i}: {r['ad_set']}")
        print(f"{'='*70}")
        print(f"\nTITLE: {r['title']}")
        print(f"\nAUDIENCE DESCRIPTION:")
        print(f"{r['audience_description']}")
        print(f"\nAD DESCRIPTION (Primary Text):")
        print(f"{r['primary_text']}")
        print(f"\nVALUE PROPOSITION: {r['value_proposition']}")
        print(f"\n--- AdCreative Agent Output ---")
        print(f"HEADLINE: {r['headline']}")
        print(f"AD ANGLE: {r['ad_angle']}")
        print(f"Color in prompt: {color_check}, Logo in prompt: {logo_check}")
        print(f"\nIMAGE PROMPT:")
        print(f"{r['image_prompt']}")

    return {
        "business_name": business_name,
        "business_type": business_type,
        "brand_color": brand_color,
        "logo_url": logo_url,
        "ad_sets_count": len(results),
        "results": results
    }


